// RenderOptions are the options of Render.
type RenderOptions struct {
	// Source is the path of the YAML relative to the page, linked from its top.
	Source string
	// Width is the width of the lines of the page, 96 by default.
	Width int
	// Root is the path from the page to the root of the repository of the rules, e.g. "../..",
	// to link the reference of each lab and the files of the teacher. When empty, they are not
	// linked.
	Root string
}

// DefaultWidth is the width of the lines of the page.
const DefaultWidth = 96

//go:embed page.md.tmpl
var pageTemplate string

var pageTmpl = template.Must(template.New("page").Parse(pageTemplate))

// Render writes the page of the rules in Markdown.
func (r *Rubric) Render(w io.Writer, opts RenderOptions) error {
	if opts.Width <= 0 {
		opts.Width = DefaultWidth
	}
	var b strings.Builder
	if err := pageTmpl.Execute(&b, r.page(opts)); err != nil {
		return err
	}
	_, err := io.WriteString(w, tidy(b.String()))
	return err
}

// page is the data of the template: the texts are wrapped already.
type page struct {
	Title       string
	Notice      string
	Intro       string
	Labs        []labView
	ScoringText string
	Late        string
	Penalties   []string
	Kinds       []string
	Origin      string
	Origins     []string
	Levels      []string
	Environment string
	EnvItems    []string
	Hygiene     string
}

type labView struct {
	ID        string
	Title     string
	Heading   string
	Anchor    string
	Deadline  string
	RuleCount int
	Facts     string
	Intro     string
	Rows      []rowView
	Rules     []ruleView
}

type rowView struct {
	ID          string
	Exercise    string
	Name        string
	Coefficient string
	Points      string
}

type ruleView struct {
	Heading     string
	Coefficient string
	Description string
	Notes       string
	Items       []string
}

func (r *Rubric) page(opts RenderOptions) page {
	w := wrapper{width: opts.Width}
	p := page{
		Title: r.Title,
		Intro: w.text(r.Intro),
	}
	if opts.Source != "" {
		p.Notice = w.wrap(fmt.Sprintf("Generated by `mc rule render` from [`%s`](%s): change the rules there, then render this page again.", opts.Source, opts.Source), "> ", "> ")
	}
	p.ScoringText = strings.TrimRight(r.Scoring.Text, "\n")
	if late := r.Scoring.LatePenalty; late.How != "" {
		p.Late = w.wrap(fmt.Sprintf("**Late work:** %s The penalty goes from %s to %s.", late.How, percent(late.Min), percent(late.Max)), "", "")
	}
	for _, penalty := range r.Scoring.Penalties {
		text := fmt.Sprintf("`%s`, %s of the points of the rule: %s", penalty.Name, percent(penalty.Remove), penalty.When)
		if penalty.How != "" {
			text += " " + penalty.How
		}
		p.Penalties = append(p.Penalties, w.item(text))
	}
	p.Kinds = w.entries(r.Evidence.Kinds)
	p.Origin = w.text(r.Evidence.Origin)
	p.Origins = w.entries(r.Evidence.Origins)
	p.Levels = w.entries(r.AnalysisLevels)
	env := r.Observations.Environment
	p.Environment = w.text(env.About)
	for _, item := range []struct{ label, text string }{
		{"OS", env.OS},
		{"Architecture", env.Arch},
		{"Cluster", env.Cluster},
	} {
		if item.text != "" {
			p.EnvItems = append(p.EnvItems, w.item(item.label+": "+item.text))
		}
	}
	p.Hygiene = w.text(r.Observations.Hygiene)

	for _, lab := range r.Labs {
		p.Labs = append(p.Labs, r.labView(lab, w, opts.Root))
	}
	return p
}

func (r *Rubric) labView(lab Lab, w wrapper, root string) labView {
	heading := fmt.Sprintf("Lab %s: %s", lab.Number(), lab.Title)
	v := labView{
		ID:       lab.ID,
		Title:    lab.Title,
		Heading:  heading,
		Anchor:   anchor(heading),
		Deadline: lab.Deadline,
		Intro:    w.text(lab.Intro),
	}
	if deadline, err := lab.DeadlineTime(); err == nil {
		v.Deadline = deadline.Format("Mon 2 Jan 2006, 15:04 (UTC-07:00)")
	}
	facts := fmt.Sprintf("**Deadline:** %s. The report of the team: `%s`.", v.Deadline, lab.Report)
	if lab.Reference != "" {
		facts += " The reference answer: " + fileLink(root, lab.Reference) + "."
	}
	v.Facts = w.wrap(facts, "", "")
	for _, rule := range r.LabRules(lab.ID) {
		v.RuleCount++
		name := rule.Name
		if rule.Optional() {
			name += ", bonus"
		}
		v.Rows = append(v.Rows, rowView{
			ID:          rule.ID,
			Exercise:    rule.Exercise,
			Name:        name,
			Coefficient: number(rule.Coefficient),
			Points:      number(rule.Points()),
		})
		v.Rules = append(v.Rules, newRuleView(rule, w, root))
	}
	return v
}

func newRuleView(rule Rule, w wrapper, root string) ruleView {
	heading := fmt.Sprintf("`%s` %s (Ex %s)", rule.ID, rule.Name, rule.Exercise)
	coefficient := fmt.Sprintf("**Coefficient:** %s (%s)", number(rule.Coefficient), points(rule.Points()))
	if rule.Optional() {
		heading += ", Bonus"
		coefficient += ", bonus"
	}
	coefficient += "."
	if rule.CoefficientReason != "" {
		coefficient += " " + rule.CoefficientReason
	}
	v := ruleView{
		Heading:     heading,
		Coefficient: w.wrap(coefficient, "", ""),
		Description: w.text(rule.Description),
	}
	if rule.Notes != "" {
		v.Notes = w.text("**Notes:** " + rule.Notes)
	}

	var items []string
	if len(rule.DependsOn) > 0 {
		items = append(items, "Depends on: "+codeList(rule.DependsOn))
	}
	for _, penalty := range rule.Penalties {
		items = append(items, fmt.Sprintf("Penalty: %s of the points when %s", percent(penalty.Remove), penalty.When))
	}
	if level := rule.Analysis.Level; level != "" && level != "none" {
		analysis := "Analysis: " + level
		if rule.Analysis.About != "" {
			analysis += ", about " + rule.Analysis.About
		}
		items = append(items, analysis)
	}
	if len(rule.Evidence.Asked) > 0 {
		items = append(items, "Evidence asked: "+evidenceList(rule.Evidence.Asked))
	}
	if len(rule.Evidence.Extra) > 0 {
		items = append(items, "Evidence observed, not in the score: "+evidenceList(rule.Evidence.Extra))
	}
	switch team, teacher := rule.Files.Team, rule.Files.Teacher; {
	case len(team) > 0 && len(teacher) > 0:
		items = append(items, fmt.Sprintf("Files of the team: %s; of the teacher: %s", codeList(team), linkList(root, teacher)))
	case len(team) > 0:
		items = append(items, "Files of the team: "+codeList(team))
	case len(teacher) > 0:
		items = append(items, "Files of the teacher: "+linkList(root, teacher))
	}
	if len(rule.Images) > 0 {
		items = append(items, "Images of the team: "+codeList(rule.Images))
	}
	for _, item := range items {
		v.Items = append(v.Items, w.item(item))
	}
	return v
}

func evidenceList(items []EvidenceItem) string {
	parts := make([]string, len(items))
	for i, item := range items {
		parts[i] = item.Kind + ", " + item.What
	}
	return strings.Join(parts, "; ")
}

func codeList(values []string) string {
	parts := make([]string, len(values))
	for i, value := range values {
		parts[i] = "`" + value + "`"
	}
	return strings.Join(parts, ", ")
}

// fileLink returns the path as code, linked from the page when the root is known.
func fileLink(root, p string) string {
	if root == "" {
		return "`" + p + "`"
	}
	return fmt.Sprintf("[`%s`](%s)", p, path.Join(root, p))
}

func linkList(root string, paths []string) string {
	parts := make([]string, len(paths))
	for i, p := range paths {
		parts[i] = fileLink(root, p)
	}
	return strings.Join(parts, ", ")
}

// number formats a coefficient or points without trailing zeros: 0.25, 5.
func number(x float64) string {
	return strconv.FormatFloat(roundHundredths(x), 'f', -1, 64)
}

func points(x float64) string {
	if x == 1 {
		return "1 point"
	}
	return number(x) + " points"
}

func percent(share float64) string {
	return number(share*100) + "%"
}

var anchorDrop = regexp.MustCompile(`[^a-z0-9 _-]`)

// anchor returns the anchor that GitHub gives to a heading.
func anchor(heading string) string {
	return strings.ReplaceAll(anchorDrop.ReplaceAllString(strings.ToLower(heading), ""), " ", "-")
}

var blankLines = regexp.MustCompile(`\n{3,}`)

// tidy keeps one blank line between the blocks, and one newline at the end.
func tidy(page string) string {
	return strings.TrimSpace(blankLines.ReplaceAllString(page, "\n\n")) + "\n"
}

// wrapper wraps the texts of the YAML at a width.
type wrapper struct {
	width int
}

// text wraps each paragraph of the text, separated by a blank line. A folded block of YAML joins
// its lines with a space, and keeps a blank line as a line break: each line is a paragraph.
func (w wrapper) text(text string) string {
	var paragraphs []string
	for _, line := range strings.Split(text, "\n") {
		if strings.TrimSpace(line) != "" {
			paragraphs = append(paragraphs, w.wrap(line, "", ""))
		}
	}
	return strings.Join(paragraphs, "\n\n")
}

// item wraps the text as an item of a list.
func (w wrapper) item(text string) string {
	return w.wrap(text, "- ", "  ")
}

func (w wrapper) entries(entries []Entry) []string {
	var items []string
	for _, entry := range entries {
		items = append(items, w.item(fmt.Sprintf("`%s`: %s", entry.Key, strings.Join(strings.Fields(entry.Text), " "))))
	}
	return items
}

// wrap wraps one paragraph: first is the prefix of its first line, indent the one of the others.
// A line never starts with a marker of Markdown, such as "- " or "1. ", which would turn the rest
// of the paragraph into a list: the word before it moves to its line.
func (w wrapper) wrap(paragraph, first, indent string) string {
	words := strings.Fields(paragraph)
	var lines [][]string
	width := len(first)
	for _, word := range words {
		n := len([]rune(word))
		if len(lines) > 0 && width+1+n > w.width {
			lines = append(lines, nil)
			width = len(indent)
		} else if len(lines) > 0 {
			width++
		}
		if len(lines) == 0 {
			lines = append(lines, nil)
		}
		last := len(lines) - 1
		lines[last] = append(lines[last], word)
		width += n
	}
	for i := 1; i < len(lines); i++ {
		if startsBlock(lines[i][0]) && len(lines[i-1]) > 1 {
			previous := lines[i-1]
			lines[i] = append([]string{previous[len(previous)-1]}, lines[i]...)
			lines[i-1] = previous[:len(previous)-1]
		}
	}
	var b strings.Builder
	for i, line := range lines {
		if i == 0 {
			b.WriteString(first)
		} else {
			b.WriteString("\n")
			b.WriteString(indent)
		}
		b.WriteString(strings.Join(line, " "))
	}
	return b.String()
}

var orderedMarker = regexp.MustCompile(`^\d+[.)]$`)

// startsBlock reports whether a line starting with the word would start a block of Markdown.
func startsBlock(word string) bool {
	switch {
	case word == "-" || word == "*" || word == "+":
		return true
	case orderedMarker.MatchString(word):
		return true
	case strings.HasPrefix(word, "#") || strings.HasPrefix(word, ">") || strings.HasPrefix(word, "|"):
		return true
	case strings.Trim(word, "=") == "" || strings.Trim(word, "-") == "":
		return true
	}
	return false
}
